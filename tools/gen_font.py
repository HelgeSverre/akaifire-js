"""Rasterises Pillow's default font, as the Python library's Canvas draws it
(mode "1", no anti-aliasing), into src/font.ts.

    cd ~/code/akai-fire-looper && uv run python ~/code/akaifire-js/tools/gen_font.py

Each glyph is stored as its advance width and one integer per row (bit 0 = leftmost pixel).
"""

import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

OUT = Path(__file__).resolve().parents[1] / "src" / "font.ts"
font = ImageFont.load_default()
chars = [chr(c) for c in range(32, 127)] + list("°±µÅÆØåæøäöüÄÖÜéè…")
ascent, descent = font.getmetrics()
height = ascent + descent

glyphs = {}
top, bottom = height, 0
for ch in chars:
    advance = max(1, round(font.getlength(ch)))
    box = font.getbbox(ch, mode="1")
    width = max(advance, box[2])
    image = Image.new("1", (width + 2, height + 4), 0)
    ImageDraw.Draw(image).text((0, 0), ch, fill=1, font=font)
    rows = []
    for y in range(image.height):
        bits = 0
        for x in range(image.width):
            if image.getpixel((x, y)):
                bits |= 1 << x
        rows.append(bits)
    used = [y for y, bits in enumerate(rows) if bits]
    if used:
        top, bottom = min(top, used[0]), max(bottom, used[-1])
    glyphs[ch] = (advance, rows)

lines = [
    "// GENERATED by tools/gen_font.py from Pillow's default font - do not edit.",
    "// The Python library draws OLED text with this font; rows are bit masks, bit 0 = left.",
    f"export const FONT_HEIGHT = {bottom - top + 1};",
    f"export const FONT_TOP = {top}; // rows above this are empty in every glyph",
    "export const FONT: Record<string, readonly [advance: number, rows: readonly number[]]> = {",
]
for ch, (advance, rows) in glyphs.items():
    key = json.dumps(ch, ensure_ascii=False)
    lines.append(f"  {key}: [{advance}, [{', '.join(str(b) for b in rows[top : bottom + 1])}]],")
lines.append("};")
OUT.write_text("\n".join(lines) + "\n")
print("glyphs", len(glyphs), "height", bottom - top + 1, "top", top, "ascent", ascent, "descent", descent)
